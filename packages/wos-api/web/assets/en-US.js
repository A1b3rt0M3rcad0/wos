export function initializeCopy(root) {
  for (const element of root.querySelectorAll("[data-copy]")) {
    const text = copy.text[element.dataset.copy];
    if (text === undefined) throw Error("Unknown product copy key");
    const node = Array.from(element.childNodes).find(
      (n) => n.nodeType === 3 && n.textContent.trim(),
    );
    if (node) node.textContent = text;
  }
  for (const attribute of ["aria-label", "title", "placeholder"])
    for (const element of root.querySelectorAll(
      "[data-copy-" + attribute + "]",
    )) {
      const value = copy.text[element.getAttribute("data-copy-" + attribute)];
      if (value === undefined) throw Error("Unknown product copy key");
      element.setAttribute(attribute, value);
    }
}

export function message(key, ...values) {
  const template = copy.text[key];
  if (template === undefined) throw Error("Unknown product message key");
  return template.replace(/\{(\d+)\}/g, (_, index) =>
    String(values[Number(index)] ?? ""),
  );
}
